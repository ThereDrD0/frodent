CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(80) NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS refresh_sessions (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS refresh_sessions_user_idx ON refresh_sessions(user_id);

CREATE TABLE IF NOT EXISTS notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notes_user_idx ON notes(user_id, id DESC);

CREATE TABLE IF NOT EXISTS boards (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES users(id),
    title VARCHAR(180) NOT NULL,
    server_seq BIGINT NOT NULL DEFAULT 0 CHECK (server_seq >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS boards_owner_updated_idx ON boards(owner_id, updated_at DESC, id);

CREATE TABLE IF NOT EXISTS board_members (
    board_id UUID NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (board_id, user_id)
);
CREATE INDEX IF NOT EXISTS board_members_user_idx ON board_members(user_id, board_id);

CREATE TABLE IF NOT EXISTS board_attachments (
    id UUID PRIMARY KEY,
    board_id UUID NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
    uploaded_by UUID NOT NULL REFERENCES users(id),
    upload_id UUID NOT NULL,
    storage_key UUID NOT NULL UNIQUE,
    original_name VARCHAR(255) NOT NULL,
    mime TEXT NOT NULL,
    size BIGINT NOT NULL CHECK (size > 0 AND size <= 20971520),
    sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (board_id, id),
    UNIQUE (board_id, uploaded_by, upload_id)
);
CREATE INDEX IF NOT EXISTS board_attachments_board_idx ON board_attachments(board_id);

CREATE TABLE IF NOT EXISTS board_objects (
    board_id UUID NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
    object_id UUID NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('sticky', 'text', 'shape', 'stroke', 'image', 'file')),
    payload JSONB NOT NULL,
    attachment_id UUID,
    revision BIGINT NOT NULL CHECK (revision > 0 AND revision <= 9007199254740991),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (board_id, object_id),
    FOREIGN KEY (board_id, attachment_id) REFERENCES board_attachments(board_id, id)
);
CREATE INDEX IF NOT EXISTS board_objects_board_idx ON board_objects(board_id, object_id);

CREATE TABLE IF NOT EXISTS board_operation_receipts (
    board_id UUID NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
    op_id UUID NOT NULL,
    actor_id UUID NOT NULL REFERENCES users(id),
    request_hash CHAR(64) NOT NULL,
    server_seq BIGINT NOT NULL,
    result JSONB NOT NULL,
    event JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (board_id, op_id),
    UNIQUE (board_id, server_seq)
);
CREATE INDEX IF NOT EXISTS board_receipts_seq_idx ON board_operation_receipts(board_id, server_seq);

CREATE TABLE IF NOT EXISTS board_invites (
    board_id UUID PRIMARY KEY REFERENCES boards(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
